import { execFile } from "node:child_process";
import { constants } from "node:fs";
import { access, lstat, open, realpath, stat } from "node:fs/promises";
import { delimiter, dirname, isAbsolute, join, relative, sep } from "node:path";
import { promisify } from "node:util";

import { HOME } from "./config.js";
import type { FileDiff } from "./types.js";

export type LocalTarget =
  | { mode: "working"; includeUntracked?: boolean }
  | { mode: "staged" | "unstaged" }
  | { mode: "compare"; base: string; head?: string };

const exec = promisify(execFile);
const MAX_GIT_BYTES = 8 * 1024 * 1024;
const MAX_FILE_BYTES = 256 * 1024;

function inside(root: string, path: string): boolean {
  const rel = relative(root, path);
  return rel !== ".." && !rel.startsWith(`..${sep}`) && !isAbsolute(rel);
}

async function repositoryRoot(cwd: string): Promise<string> {
  let root = await realpath(cwd);
  for (;;) {
    const marker = await lstat(join(root, ".git")).catch(() => null);
    if (marker?.isDirectory() || marker?.isFile()) return root;
    const parent = dirname(root);
    if (parent === root) throw new Error("No Git working tree found. Run inside a repository.");
    root = parent;
  }
}

async function gitExecutable(root: string): Promise<string> {
  const name = process.platform === "win32" ? "git.exe" : "git";
  const searchPath = Object.entries(process.env).find(([key]) => key.toUpperCase() === "PATH")?.[1];
  for (const folder of (searchPath ?? "").split(delimiter)) {
    if (!isAbsolute(folder) || inside(root, folder)) continue;
    const candidate = await realpath(join(folder, name)).catch(() => null);
    if (!candidate || inside(root, candidate)) continue;
    try {
      await access(candidate, constants.X_OK);
      if ((await stat(candidate)).isFile()) return candidate;
    } catch {
      // Continue searching PATH for an executable installation.
    }
  }
  throw new Error("Git is required for local reviews. Add its installation directory to PATH.");
}

/** Separate the NUL-delimited raw paths from the patches generated by the same
 * diff invocation. Patch headers may quote filenames, so use the raw paths. */
function parseRawDiff(output: string): FileDiff[] {
  if (!output) return [];
  const boundary = output.indexOf("\0\0");
  if (boundary < 0) throw new Error("Git returned an unexpected diff format.");
  const fields = output.slice(0, boundary).split("\0");
  const patches = output.slice(boundary + 2).split(/(?=^diff --git )/m);
  const diffs: FileDiff[] = [];
  for (let i = 0; i < fields.length; ) {
    const raw = /^:[0-7]+ [0-7]+ [\da-f]+ [\da-f]+ ([A-Z])\d*$/.exec(fields[i++]);
    const oldPath = fields[i++];
    if (!raw || !oldPath) throw new Error("Git returned an unexpected file record.");
    const status = raw[1];
    const newPath = status === "R" || status === "C" ? fields[i++] : oldPath;
    const diff = patches[diffs.length];
    if (!newPath || !diff?.startsWith("diff --git ")) {
      throw new Error("Git returned an incomplete diff. Resolve unmerged files and retry.");
    }
    diffs.push({ oldPath, newPath, diff, newFile: status === "A", deletedFile: status === "D" });
  }
  if (diffs.length !== patches.length) throw new Error("Git returned an incomplete patch set.");
  return diffs;
}

export async function readLocalChanges(cwd: string, target: LocalTarget, signal?: AbortSignal) {
  const root = await repositoryRoot(cwd);
  const executable = await gitExecutable(root);
  const dataHome = await realpath(HOME).catch(() => null);
  // Ignore inherited Git routing and executable settings. Pin the work tree to
  // the discovered root because local config can otherwise redirect it.
  const env = Object.fromEntries(
    Object.entries(process.env).filter(([name]) => !/^GIT_/i.test(name)),
  );
  env.GIT_CONFIG_NOSYSTEM = "1";
  env.GIT_CONFIG_GLOBAL = process.platform === "win32" ? "NUL" : "/dev/null";
  env.GIT_NO_LAZY_FETCH = "1";
  env.LC_ALL = "C";
  const git = async (
    args: string[],
    options: { acceptedExitCodes?: number[]; maxBuffer?: number } = {},
  ) => {
    try {
      const child = exec(
        executable,
        [
          "--no-pager",
          "--no-optional-locks",
          "--work-tree",
          root,
          "-c",
          "core.fsmonitor=false",
          ...args,
        ],
        {
          cwd: root,
          env,
          encoding: "utf8",
          windowsHide: true,
          maxBuffer: options.maxBuffer ?? MAX_GIT_BYTES,
          timeout: 30_000,
          signal,
        },
      );
      child.child.stdin?.end();
      return (await child).stdout;
    } catch (error) {
      const err = error as { code?: unknown; killed?: boolean };
      const cause = { cause: error };
      if (signal?.aborted) throw new Error("Review cancelled.", cause);
      if (typeof err.code === "number" && options.acceptedExitCodes?.includes(err.code))
        return null;
      if (err.code === "ENOENT") throw new Error("Git is required for local reviews.", cause);
      if (err.code === "ERR_CHILD_PROCESS_STDIO_MAXBUFFER")
        throw new Error(
          "Git output exceeded the review size limit. Select a smaller comparison.",
          cause,
        );
      if (err.killed) throw new Error("Git exceeded the 30-second command timeout.", cause);
      throw new Error(
        "Git could not read this comparison. Check repository ownership, refs, and index state.",
        cause,
      );
    }
  };

  const resolveCommit = async (ref: string) => {
    if (!ref || ref.includes("\0")) throw new Error("Invalid Git revision.");
    const sha = (
      await git(["rev-parse", "--verify", "--end-of-options", `${ref}^{commit}`], {
        acceptedExitCodes: [1, 128],
      })
    )?.trim();
    if (!sha || !/^[\da-f]{40,64}$/.test(sha))
      throw new Error("Git revision does not resolve to a commit.");
    return sha;
  };

  const isWorktree = target.mode === "working" || target.mode === "unstaged";
  if (target.mode !== "compare" && (await git(["ls-files", "--unmerged", "-z"]))) {
    throw new Error("Resolve unmerged files before reviewing the working tree or index.");
  }
  const filterOverrides = new Set<string>();
  if (isWorktree) {
    const keys = await git(
      [
        "config",
        "--null",
        "--name-only",
        "--get-regexp",
        "^filter\\..*\\.(clean|process|required)$",
      ],
      { acceptedExitCodes: [1] },
    );
    for (const key of (keys ?? "").split("\0")) {
      if (key) filterOverrides.add(`${key}=${key.endsWith(".required") ? "false" : ""}`);
    }
  }
  let headSha = target.mode === "staged" ? "index" : "working-tree";
  let revisions: string[];
  if (target.mode === "compare") {
    const base = await resolveCommit(target.base);
    headSha = await resolveCommit(target.head ?? "HEAD");
    revisions = [base, headSha];
  } else if (target.mode === "staged") {
    revisions = ["--cached"];
  } else if (target.mode === "working") {
    const head = await git(["rev-parse", "--verify", "--end-of-options", "HEAD^{commit}"], {
      acceptedExitCodes: [1, 128],
    });
    const tree = head ?? (await git(["hash-object", "-t", "tree", "--stdin"]));
    if (!tree) throw new Error("Git could not identify the comparison base.");
    revisions = [tree.trim()];
  } else {
    revisions = [];
  }
  const output = await git([
    ...[...filterOverrides].flatMap((setting) => ["-c", setting]),
    "diff",
    "--raw",
    "-z",
    "--patch",
    "--no-color",
    "--no-ext-diff",
    "--no-textconv",
    "--ignore-submodules=all",
    "--find-renames",
    "--find-copies",
    "--diff-filter=ACDMRT",
    "--src-prefix=a/",
    "--dst-prefix=b/",
    ...revisions,
    "--",
  ]);
  const diffs = parseRawDiff(output ?? "");

  async function worktreeFile(path: string): Promise<string | null> {
    try {
      const file = join(root, ...path.split("/"));
      if (!inside(root, file)) return null;
      const resolved = await realpath(file);
      if (
        relative(file, resolved) ||
        (dataHome && inside(dataHome, resolved)) ||
        !(await lstat(file)).isFile()
      )
        return null;
      const handle = await open(
        file,
        constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0) | (constants.O_NONBLOCK ?? 0),
      );
      try {
        const stat = await handle.stat();
        if (!stat.isFile() || stat.size > MAX_FILE_BYTES) return null;
        const bytes = Buffer.alloc(stat.size + 1);
        const { bytesRead } = await handle.read(bytes, 0, bytes.length, 0);
        const data = bytes.subarray(0, bytesRead);
        return bytesRead > MAX_FILE_BYTES || data.includes(0) ? null : data.toString("utf8");
      } finally {
        await handle.close();
      }
    } catch {
      return null;
    }
  }

  if (target.mode === "working" && target.includeUntracked) {
    const untracked = await git(["ls-files", "--others", "--exclude-standard", "-z", "--"]);
    let budget = MAX_GIT_BYTES - Buffer.byteLength(output ?? "");
    for (const path of (untracked ?? "").split("\0").filter(Boolean)) {
      signal?.throwIfAborted();
      const content = budget > 0 ? await worktreeFile(path) : null;
      const lines = content ? content.replace(/\n$/, "").split("\n") : [];
      const diff = lines.length
        ? `@@ -0,0 +1,${lines.length} @@\n${lines.map((line) => `+${line}`).join("\n")}\n`
        : "";
      budget -= Buffer.byteLength(diff);
      diffs.push({
        oldPath: path,
        newPath: path,
        diff: budget >= 0 ? diff : "",
        newFile: true,
        deletedFile: false,
      });
    }
  }

  const getFile = async (_project: string, path: string) => {
    if (
      isAbsolute(path) ||
      (process.platform === "win32" && /[:\\]/.test(path)) ||
      path
        .split("/")
        .some((part) => !part || part === "." || part === ".." || part.toLowerCase() === ".git")
    )
      return null;
    if (isWorktree) return worktreeFile(path);
    const revision = target.mode === "staged" ? "" : headSha;
    try {
      const object = await git(["cat-file", "blob", `${revision}:${path}`], {
        acceptedExitCodes: [1, 128],
        maxBuffer: MAX_FILE_BYTES,
      });
      return object?.includes("\0") ? null : object;
    } catch {
      return null;
    }
  };
  return {
    root,
    headSha,
    diffs,
    getFile,
    async searchBlobs() {
      return [];
    },
  };
}
